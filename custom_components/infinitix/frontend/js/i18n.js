export function makeT(lang) {
  const dict = STRINGS[lang] || STRINGS.he;
  const fallback = STRINGS.en;
  return (key, vars) => {
    let s = dict[key] ?? fallback[key] ?? key;
    if (vars && typeof s === "string") for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
  };
}
